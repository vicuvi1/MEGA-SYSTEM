import { contextBridge, ipcRenderer } from 'electron'
import type { DesktopApi } from '../shared/desktop'

const api: DesktopApi = {
  load: () => ipcRenderer.invoke('desktop:load'),
  save: (bytes) => ipcRenderer.invoke('desktop:save', bytes),
  backup: () => ipcRenderer.invoke('desktop:backup'),
  updateStatus: () => ipcRenderer.invoke('desktop:updateStatus'),
  checkUpdates: () => ipcRenderer.invoke('desktop:checkUpdates'),
  installUpdate: () => ipcRenderer.invoke('desktop:installUpdate'),
  rollback: () => ipcRenderer.invoke('desktop:rollback'),
  notify: (n: { id: string; title: string; body?: string | null }) => ipcRenderer.invoke('desktop:notify', n),
  onNotifClick: (cb: (id: string) => void) => void ipcRenderer.on('desktop:notif-click', (_e, id) => cb(String(id))),
  onUpdateStatus: (cb: (s: any) => void) => void ipcRenderer.on('desktop:update', (_e, s) => cb(s)),
  loginGithub: () => ipcRenderer.invoke('desktop:loginGithub'),
  titleBar: (color, symbol) => ipcRenderer.send('desktop:titlebar', color, symbol),
  onCrashes: (cb) => void ipcRenderer.on('desktop:crashes', (_e, list) => cb(list)),
  backupStatus: () => ipcRenderer.invoke('backups:status'),
  writeBackup: (text, day) => ipcRenderer.invoke('backups:write', text, day),
  readBackup: (where, name) => ipcRenderer.invoke('backups:read', where, name),
  chooseBackupFolder: () => ipcRenderer.invoke('backups:choose'),
  openBackupFolder: (where) => ipcRenderer.invoke('backups:open', where),
  islandState: (s) => ipcRenderer.send('island:state', s),
  onIslandAction: (cb) => void ipcRenderer.on('island:action', (_e, a) => cb(a)),
  onNavigate: (cb) => void ipcRenderer.on('app:navigate', (_e, page) => cb(page)),
  onAway: (cb) => void ipcRenderer.on('desktop:away', (_e, a) => cb(a)),
  onIdle: (cb) => void ipcRenderer.on('desktop:idle', (_e, sec) => cb(Number(sec) || 0)),
  onClip: (cb) => void ipcRenderer.on('desktop:clip', (_e, t) => cb(String(t ?? ''))),
  onIslandState: (cb) => void ipcRenderer.on('island:state', (_e, s) => cb(s)),
  islandAction: (a) => ipcRenderer.send('island:action', a),
  islandAck: (ack) => ipcRenderer.send('island:ack', ack),
  onIslandAck: (cb) => void ipcRenderer.on('island:ack', (_e, ack) => cb(ack)),
  islandFocus: () => ipcRenderer.send('island:focus'),
  getIslandPrefs: () => ipcRenderer.invoke('island:getPrefs'),
  setIslandPrefs: (p) => ipcRenderer.invoke('island:setPrefs', p),
  onIslandPrefs: (cb) => void ipcRenderer.on('island:prefs', (_e, p) => cb(p)),
  islandKeyboard: (on) => ipcRenderer.send('island:keyboard', !!on),
  onIslandBlur: (cb) => void ipcRenderer.on('island:blur', () => cb()),
  islandQuiet: (choice) => ipcRenderer.send('island:quiet', choice),
  onIslandQuiet: (cb) => void ipcRenderer.on('island:quiet', (_e, q) => cb(q)),
  islandHot: (rect) => ipcRenderer.send('island:hot', rect),
  islandDrag: (on) => ipcRenderer.send(on ? 'island:dragStart' : 'island:dragEnd'),
  onIslandHover: (cb) => void ipcRenderer.on('island:hover', (_e, over) => cb(!!over)),
  onIslandPlacement: (cb) => void ipcRenderer.on('island:placement', (_e, p) => cb(p)),
  onIslandToggle: (cb) => void ipcRenderer.on('island:toggle', () => cb()),
  islandReady: () => ipcRenderer.send('island:ready'),
  showApp: (page) => ipcRenderer.send('island:showApp', page)
}
contextBridge.exposeInMainWorld('desktop', api)
